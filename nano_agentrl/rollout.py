"""Batched multi-turn rollouts: generate -> <search> -> retrieve -> <information> -> continue.

Implements the interleaved reasoning-and-search rollout of Search-R1 Sec. 3.1-3.2,
including the retrieved-token loss mask (Sec. 3.1, "Loss Masking for Retrieved Tokens").
The multi-turn loop is added in milestone 2 (P10); this module already defines the
Trajectory record that every rollout (single- or multi-turn) produces.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Trajectory:
    """One sampled response to one prompt.

    prompt_ids:    the tokenized prompt.
    response_ids:  every token after the prompt, in order: policy tokens AND, in the
                   search task, the environment's <information> tokens.
    response_mask: same length as response_ids. 1 = generated by the policy (trained on),
                   0 = inserted by the environment (never trained on).
    """

    prompt_index: int
    prompt_ids: list[int]
    response_ids: list[int]
    response_mask: list[int]
    text: str  # decoded response (policy + environment text)
    golds: list[str] = field(default_factory=list)
    finish_reason: str = ""  # "answer", "stop", "eos", "length", "max_turns"
    num_searches: int = 0
    num_invalid: int = 0
    reward: float = 0.0
